export const DEFAULT_THEME_ID = 'default';

export const isKnownTheme = (id: unknown): id is string =>
  typeof id === 'string' && Object.prototype.hasOwnProperty.call(THEMES, id);

export const getTheme = (id: string | undefined | null): ThemeTokens =>
  (id && THEMES[id]) || THEMES[DEFAULT_THEME_ID];

export const listThemes = (): ThemeTokens[] => Object.values(THEMES);
